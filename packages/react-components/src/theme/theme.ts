const fontFamilyTokens: FontFamilyTokens = {
  fontFamilyBase:
    'Aptos, Inter, Helvetica, Arial, system-ui, -apple-system, BlinkMacSystemFont, sans-serif',
  fontFamilyMonospace: '"Aptos Mono", Menlo, Monaco, Consolas, monospace',
  fontFamilyNumeric:
    'Aptos, Inter, Helvetica, Arial, system-ui, -apple-system, BlinkMacSystemFont, sans-serif',
};

export type CoreAITheme = Theme & CoreAITokens;

export const createCoreAILightTheme = (brandVariants: BrandVariants): CoreAITheme => {
  return {
    ...createLightTheme(brandVariants),
    ...neutralStrokeLightTheme,
    ...coreaiTokensLightTheme,
    ...fontFamilyTokens,
  };
};

export const createCoreAIDarkTheme = (brandVariants: BrandVariants): CoreAITheme => {
  return {
    ...createDarkTheme(brandVariants),
    ...neutralBackgroundDarkTheme,
    ...neutralStrokeDarkTheme,
    ...coreaiTokensDarkTheme,
    ...fontFamilyTokens,
  };
};

export const coreaiLightTheme: CoreAITheme = {
  ...createCoreAILightTheme(coreaiBrandVariants),
  ...brandBackgroundLightTheme,
};

export const coreaiDarkTheme: CoreAITheme = {
  ...createCoreAIDarkTheme(coreaiBrandVariants),
  ...brandForegroundDarkTheme,
};

