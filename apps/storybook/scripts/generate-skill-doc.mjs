// Mirrors packages/react-components/agent/SKILL.md — the canonical,
// npm-shipped agent-usage doc — into a generated `src/stories/docs/AgentSkill.mdx`
// page, so the same authored source is also addressable through the MCP tools
// without hand-maintaining a second copy that can drift (see
// apps/storybook/README.md's "Agent Skill mirror" section).
//
// `agent/SKILL.md` is the single source of truth; `AgentSkill.mdx` is a
// generated build artifact (gitignored — see .gitignore) that must never be
// hand-edited. It's regenerated:
//   - once via `storybook:prepare` during `dev`/`build` (see package.json)
//   - live, on every save, by a Vite dev-server watcher (see .storybook/main.ts)
//   - on demand: `npm run docs:skill`
//
// Usage: node scripts/generate-skill-doc.mjs
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const skillPath = path.resolve(__dirname, '../../../packages/react-components/agent/SKILL.md');
const outPath = path.resolve(__dirname, '../src/stories/docs/AgentSkill.mdx');

/** Strips the leading `--- ... ---` YAML frontmatter block, if present. */
function stripFrontmatter(source) {
  const match = source.match(/^---\r?\n[\s\S]*?\r?\n---\r?\n/);
  return match ? source.slice(match[0].length) : source;
}

export function generateSkillDoc() {
  const source = fs.readFileSync(skillPath, 'utf8');
  const body = stripFrontmatter(source).trimStart();
  const mdx = `{/* AUTO-GENERATED by scripts/generate-skill-doc.mjs — do not edit by hand.
   Source of truth: packages/react-components/agent/SKILL.md. Regenerated on dev/build start and on save. */}
import { Meta } from '@storybook/addon-docs/blocks';

<Meta title="Docs/Agent Skill" summary="Distributable agent-usage guide for @coreai-ds/react-components (also shipped as agent/SKILL.md in the npm package)." />

${body}`;
  fs.writeFileSync(outPath, mdx);
  return outPath;
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  const written = generateSkillDoc();
  console.log(`generated ${path.relative(process.cwd(), written)}`);
}
