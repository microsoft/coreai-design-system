import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateCatalog } from './validate-illicons.mjs';

export function generateIllicons(directory, output) {
  const manifest = validateCatalog(directory);
  const entries = manifest.icons.map(({ title, tags, file }) => {
    const id = file.slice(0, -4);
    const src = `data:image/svg+xml;base64,${readFileSync(path.join(directory, file)).toString('base64')}`;
    return `  ${JSON.stringify({ id, name: title, tags, src })}`;
  });
  const source = `// Copyright (c) Microsoft Corporation.
// Licensed under the MIT license.

// Generated by scripts/generate-illicons.mjs. Edit illicons/manifest.json instead.
export type IlliconName = ${manifest.icons.map(({ file }) => JSON.stringify(file.slice(0, -4))).join(' | ') || 'never'};

export interface IlliconDefinition {
  readonly id: IlliconName;
  readonly name: string;
  readonly tags: readonly string[];
  readonly src: string;
}

export const illicons: readonly IlliconDefinition[] = [
${entries.join(',\n')}
];
`;
  if (!existsSync(output) || readFileSync(output, 'utf8') !== source) {
    writeFileSync(output, source);
  }
  return manifest;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  generateIllicons(
    fileURLToPath(new URL('../packages/react-components/illicons/', import.meta.url)),
    fileURLToPath(
      new URL('../packages/react-components/src/illicons.generated.ts', import.meta.url),
    ),
  );
}
